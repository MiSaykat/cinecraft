function initBiamsDashboard() {
  const tbody = document.getElementById('biamsTableBody');
  const searchInput = document.getElementById('biamsSearchInput');
  const printBtn = document.getElementById('biamsPrintBtn');

  if (!tbody) return;

  renderBiamsTable(BIAMS_ASSETS);

  if (searchInput) {
    searchInput.addEventListener('input', (e) => {
      const q = e.target.value.toLowerCase().trim();
      const filtered = BIAMS_ASSETS.filter(a => {
        const nameBn = (a.name_bn || a.name || '').toLowerCase();
        const nameEn = (a.name_en || '').toLowerCase();
        const distBn = (a.dist_bn || a.dist || '').toLowerCase();
        const distEn = (a.dist_en || '').toLowerCase();
        const id = (a.id || '').toLowerCase();
        const type = (a.type || '').toLowerCase();
        return id.includes(q) || 
               nameBn.includes(q) || 
               nameEn.includes(q) || 
               distBn.includes(q) || 
               distEn.includes(q) || 
               type.includes(q);
      });
      renderBiamsTable(filtered);
    });
  }

  if (printBtn) {
    printBtn.addEventListener('click', () => {
      window.print();
    });
  }
}

function getShiClass(shiStr) {
  const val = parseInt(shiStr, 10);
  if (isNaN(val)) return 'fair';
  if (val < 70) return 'attention'; // Red: Lowest (< 70%)
  if (val <= 85) return 'fair';     // Yellow/Amber: Medium (70-85%)
  return 'good';                    // Green: High (> 85%)
}

function renderBiamsTable(items) {
  const tbody = document.getElementById('biamsTableBody');
  if (!tbody) return;

  tbody.innerHTML = '';
  items.forEach(it => {
    const tr = document.createElement('tr');
    const shiClass = getShiClass(it.shi);
    const name = currentLang === 'bn' ? (it.name_bn || it.name) : (it.name_en || it.name);
    const dist = currentLang === 'bn' ? (it.dist_bn || it.dist) : (it.dist_en || it.dist);
    const rec = currentLang === 'bn' ? (it.rec_bn || it.rec) : (it.rec_en || it.rec);
    tr.innerHTML = `
      <td><strong style="color:var(--primary);">${it.id}</strong></td>
      <td><strong>${name}</strong></td>
      <td>${dist}</td>
      <td>${it.type}</td>
      <td>${it.spans}</td>
      <td>${it.last_audit}</td>
      <td><span class="badge-status ${shiClass}">${it.shi}</span></td>
      <td>${rec}</td>
    `;
    tbody.appendChild(tr);
  });
}

