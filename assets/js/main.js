function switchVideo(key) {
  const data = VIDEO_CATALOG[key];
  const iframe = document.getElementById('mainTheaterIframe');
  const player = document.getElementById('mainTheaterVideo');
  if (!iframe && !player) return;
  const chaptersContainer = document.getElementById('videoChaptersBar');
  const flightIdEl = document.getElementById('hudFlightId');
  const coordsEl = document.getElementById('hudCoords');
  const targetTagEl = document.getElementById('hudTargetTag');

  if (!data) return;
  if (iframe) {
    iframe.src = data.src;
  } else if (player) {
    player.poster = data.poster;
    player.src = data.src;
    player.load();
  }

  // Update Aerospace Mission Control HUD Telemetry
  if (flightIdEl) {
    flightIdEl.textContent = key === 'kushtia'
      ? 'MISSION FEED 01: GORAI TRUSS [LGED]'
      : 'MISSION FEED 02: MULTI-SPAN GIRDER [LGED & RHD]';
  }
  if (coordsEl) {
    coordsEl.textContent = key === 'kushtia'
      ? "GPS: 23°54'31.7\"N 89°07'19.6\"E"
      : "GPS: 22°42'18.2\"N 90°22'31.5\"E";
  }
  if (targetTagEl) {
    targetTagEl.textContent = key === 'kushtia'
      ? 'SCAN TARGET: TRUSS GUSSET NODE #04'
      : 'SCAN TARGET: ELASTOMERIC BEARING PAD #02';
  }

  if (chaptersContainer) {
    chaptersContainer.innerHTML = '';
    data.chapters.forEach(ch => {
      const card = document.createElement('div');
      card.className = 'chapter-card';
      const label = currentLang === 'bn' ? ch.label_bn : ch.label_en;
      card.innerHTML = `
        <span class="time">⏱ ${formatSeconds(ch.time)}</span>
        <span class="desc">${label.split('•')[1] || label}</span>
      `;
      card.addEventListener('click', () => {
        player.currentTime = ch.time;
        player.play();
        playAudioChime(500, 'sine', 0.08);
      });
      chaptersContainer.appendChild(card);
    });
  }
}

function formatSeconds(sec) {
  const m = Math.floor(sec / 60);
  const s = Math.floor(sec % 60);
  return `${m < 10 ? '0' : ''}${m}:${s < 10 ? '0' : ''}${s}`;
}

