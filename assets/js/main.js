function initGisMap() {
  const pins = document.querySelectorAll('.map-pin');
  pins.forEach(pin => {
    pin.addEventListener('click', function() {
      const cityKey = this.getAttribute('data-city');
      pins.forEach(p => p.classList.remove('selected'));
      this.classList.add('selected');
      loadGisDossier(cityKey);
      playAudioChime(620, 'sine', 0.1);
    });
  });

  const rangpurPin = document.querySelector('.map-pin[data-city="rangpur"]');
  if (rangpurPin) rangpurPin.classList.add('selected');
  loadGisDossier('rangpur');
}

function loadGisDossier(key) {
  const p = GIS_PROJECTS[key];
  if (!p) return;

  document.getElementById('dossierCityName').innerText = currentLang === 'bn' ? p.name_bn : p.name_en;
  document.getElementById('dossierZone').innerText = currentLang === 'bn' ? p.zone_bn : p.zone_en;
  document.getElementById('dossierBridgesVal').innerText = currentLang === 'bn' ? p.bridges_bn : p.bridges_en;
  document.getElementById('dossierDateVal').innerText = currentLang === 'bn' ? p.last_date_bn : p.last_date_en;
  document.getElementById('dossierDroneVal').innerText = p.drone;
  const statusEl = document.getElementById('dossierStatusVal');
  if (statusEl) {
    statusEl.innerText = currentLang === 'bn' ? p.status_bn : p.status_en;
    statusEl.style.color = key === 'rangpur' ? 'var(--accent-gold)' : 'var(--accent-cyan)';
  }
  document.getElementById('dossierNotes').innerText = currentLang === 'bn' ? p.notes_bn : p.notes_en;
}

