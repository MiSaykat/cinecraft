/* ==========================================================================
   1. DARK & LIGHT THEME ENGINE
   ========================================================================== */
let currentTheme = 'dark';

function initThemeEngine() {
  const themeBtn = document.getElementById('themeToggleBtn');
  const savedTheme = localStorage.getItem('cinecraft_theme');
  if (savedTheme === 'light' || savedTheme === 'dark') {
    currentTheme = savedTheme;
  } else {
    currentTheme = 'dark';
  }
  applyTheme(currentTheme);

  if (themeBtn) {
    themeBtn.addEventListener('click', () => {
      currentTheme = currentTheme === 'dark' ? 'light' : 'dark';
      localStorage.setItem('cinecraft_theme', currentTheme);
      applyTheme(currentTheme);
      playAudioChime(currentTheme === 'light' ? 660 : 380, 'sine', 0.12);
    });
  }
}

function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
  const themeBtn = document.getElementById('themeToggleBtn');
  if (themeBtn) {
    themeBtn.innerHTML = theme === 'dark' ? '☀️' : '🌙';
    themeBtn.title = currentLang === 'bn' 
      ? (theme === 'dark' ? 'লাইট মোডে পরিবর্তন করুন' : 'ডার্ক মোডে পরিবর্তন করুন')
      : (theme === 'dark' ? 'Switch to Light Mode' : 'Switch to Dark Mode');
  }
}

