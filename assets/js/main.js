function moveMagnifier(e) {
  const viewArea = document.getElementById('lensViewArea');
  const magCircle = document.getElementById('magnifierCircle');
  const rect = viewArea.getBoundingClientRect();
  
  let x = e.clientX - rect.left;
  let y = e.clientY - rect.top;

  if (x < 0) x = 0;
  if (y < 0) y = 0;
  if (x > rect.width) x = rect.width;
  if (y > rect.height) y = rect.height;

  const w = magCircle.offsetWidth / 2;
  const h = magCircle.offsetHeight / 2;

  magCircle.style.left = `${x - w}px`;
  magCircle.style.top = `${y - h}px`;

  const bgX = (x / rect.width) * 100;
  const bgY = (y / rect.height) * 100;
  magCircle.style.backgroundPosition = `${bgX}% ${bgY}%`;
  magCircle.style.backgroundSize = `${rect.width * currentZoom}px ${rect.height * currentZoom}px`;
}

