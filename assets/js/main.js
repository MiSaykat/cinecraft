function initGalleryAndLightbox() {
  const grid = document.getElementById('galleryGrid');
  const filterBtns = document.querySelectorAll('.filter-btn');
  const modal = document.getElementById('lightboxModal');
  const closeBtn = document.getElementById('lightboxCloseBtn');

  if (!grid) return;

  renderGallery('all');

  filterBtns.forEach(btn => {
    btn.addEventListener('click', function() {
      filterBtns.forEach(b => b.classList.remove('active'));
      this.classList.add('active');
      const cat = this.getAttribute('data-cat');
      renderGallery(cat);
      playAudioChime(480, 'sine', 0.08);
    });
  });

  if (closeBtn && modal) {
    closeBtn.addEventListener('click', () => {
      modal.classList.remove('active');
    });
    modal.addEventListener('click', (e) => {
      if (e.target === modal) modal.classList.remove('active');
    });
  }

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape' && modal.classList.contains('active')) {
      modal.classList.remove('active');
    }
  });
}

function renderGallery(cat) {
  const grid = document.getElementById('galleryGrid');
  if (!grid) return;

  grid.innerHTML = '';
  const items = cat === 'all' 
    ? GALLERY_ITEMS 
    : GALLERY_ITEMS.filter(it => it.cat === cat || it.client === cat);

  items.forEach(it => {
    const card = document.createElement('div');
    card.className = 'gallery-item-card';

    let clientBadgeClass = it.client || 'lged';
    let clientBadgeText = '';
    if (it.client === 'pwd') clientBadgeText = currentLang === 'bn' ? 'গণপূর্ত (PWD)' : 'PWD';
    else clientBadgeText = currentLang === 'bn' ? 'এলজিইডি (LGED)' : 'LGED';

    const compLabel = it.cat.replace('_', ' ').toUpperCase();

    card.innerHTML = `
      <div class="gallery-item-thumb">
        <img src="assets/thumbnails/${it.file}" alt="${it.title_en}" loading="lazy">
        <span class="gallery-client-pill ${clientBadgeClass}">${clientBadgeText}</span>
      </div>
      <div class="gallery-item-body">
        <span class="gallery-item-cat ${clientBadgeClass}">${clientBadgeText} • ${compLabel}</span>
        <div class="gallery-item-title">${currentLang === 'bn' ? it.title_bn : it.title_en}</div>
        <div class="gallery-item-desc">${currentLang === 'bn' ? it.desc_bn : it.desc_en}</div>
      </div>
    `;

    card.addEventListener('click', () => {
      openLightbox(it);
      playAudioChime(550, 'sine', 0.1);
    });

    grid.appendChild(card);
  });
}

function openLightbox(item) {
  const modal = document.getElementById('lightboxModal');
  const img = document.getElementById('lightboxImg');
  const title = document.getElementById('lightboxTitle');
  const desc = document.getElementById('lightboxDesc');
  const exif = document.getElementById('lightboxExif');

  if (!modal || !img) return;

  img.src = `assets/images/${item.file}`;
  title.innerText = currentLang === 'bn' ? item.title_bn : item.title_en;
  desc.innerText = currentLang === 'bn' ? item.desc_bn : item.desc_en;
  exif.innerText = currentLang === 'bn'
    ? 'ক্যামেরা ড্রোন: DJI Mavic 4 Pro • ১০০ মেগাপিক্সেল অপটিক্যাল • 4K D-Log / Rec.709'
    : 'Camera Drone: DJI Mavic 4 Pro • 100MP Optical • 4K D-Log / Rec.709';

  modal.classList.add('active');
}

